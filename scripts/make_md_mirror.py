#!/usr/bin/env python3
"""Regenerate Writeup.md (GitHub-flavoured Markdown mirror of Writeup.tex) with pandoc.

The .tex is preprocessed so that pandoc does not read tmlr.sty (which it cannot parse), the
script-generated tables are inlined through \\input, and figures point at web-renderable files.
Run from the project root: python scripts/make_md_mirror.py
"""
import re
import subprocess
import sys
import time
from pathlib import Path

BASE = Path(__file__).parent.parent
TEX = BASE / 'Writeup.tex'
OUT = BASE / 'Writeup.md'
TMP = BASE / '_Writeup_mirror.tex'


def preprocess(src: str) -> str:
    src = src.replace('\\usepackage[preprint]{tmlr}', '')
    src = re.sub(r'\\author\{.*?\}\n', '\\\\author{David Benson, Columbia University}\n', src, flags=re.S)
    src = re.sub(r'\\resizebox\{\\textwidth\}\{!\}\{(\\input\{[^}]*\})\}', r'\1', src)
    src = re.sub(r'\\paragraph\{([^}]*)\}', r'\\medskip\\noindent\\textbf{\1}', src)
    src = src.replace('figures/eval_pipeline.pdf', 'figures/eval_pipeline.svg')
    return src


def main():
    tex = preprocess(TEX.read_text())
    TMP.write_text(tex)
    try:
        md = subprocess.run(['pandoc', str(TMP), '-f', 'latex', '-t', 'gfm', '--citeproc', '--bibliography', str(BASE / 'references.bib'),
                             '--wrap=none', '--markdown-headings=atx'], cwd=BASE, capture_output=True, text=True, check=True).stdout
    finally:
        TMP.unlink(missing_ok=True)
    title = re.search(r'\\title\{(.*?)\}', TEX.read_text()).group(1)
    md = md.replace('<span id="', '<a id="').replace('" label="', '" name="')   # anchors that GitHub renders
    md = re.sub(r'<a id="([^"]*)" name="[^"]*"></span>', r'<a id="\1"></a>', md)
    header = (f"# {title}\n\nDavid Benson, Columbia University\n\n"
              f"> Markdown mirror of `Writeup.tex`, generated by `scripts/make_md_mirror.py` on {time.strftime('%Y-%m-%d')} "
              f"(every table is produced by `scripts/make_tex_tables.py` from the result files under `outputs/`). "
              f"The typeset version is [Writeup.pdf](./Writeup.pdf).\n\n")
    OUT.write_text(header + md)
    print(f"wrote {OUT} ({len(md.splitlines())} lines, {md.count('<table>')} html tables, {md.count('|---') + md.count('|:--')} md tables)")


if __name__ == '__main__':
    main()
